import { describe, expect, it } from 'vitest'
import { analyze, GcodeScanner, macroParams, type PrinterFacts } from './gcodeCheck'

const facts: PrinterFacts = {
  commands: new Set(['G1', 'G90', 'G21', 'M83', 'M104', 'M106', 'M140', 'T0', 'T1', 'PRINT_START', 'PRINT_END', 'M73', 'SET_VELOCITY_LIMIT']),
  tools: [
    { number: 0, nozzle: 0.4, name: 'tool T0' },
    { number: 1, nozzle: 0.4, name: 'tool T1' },
  ],
  printStartParams: new Set(['TOOL', 'TOOL_TEMP', 'BED_TEMP']),
  sections: new Set(),
}

function scan(text: string, snippet = false) {
  const s = new GcodeScanner(snippet)
  // feed in odd-sized chunks to exercise line carry-over
  for (let i = 0; i < text.length; i += 7) s.push(text.slice(i, i + 7))
  return s.end()
}

const ORCA = `; generated by OrcaSlicer 2.3.0 on 2026-10-01
PRINT_START BED_TEMP=55 TOOL=1 TOOL_TEMP=220 T0_TEMP=220
G90
G21
M83 ; relative
T1
M104 S220 ; temp
G1 X10 Y10 E1
G2 X1 Y1 I1 J1
M191 S40
T3
M73 P10
PRINT_END
; CONFIG_BLOCK_START
; nozzle_diameter = 0.6
; single_extruder_multi_material = 1
; extruder_offset = 0x0
; CONFIG_BLOCK_END
`

describe('GcodeScanner', () => {
  it('collects commands across chunk boundaries', () => {
    const r = scan(ORCA)
    expect(r.commands.get('G1')!.count).toBe(1)
    expect([...r.toolsUsed].sort()).toEqual([1, 3])
    expect(r.settings.get('nozzle_diameter')).toBe('0.6')
    expect(r.slicer).toMatch(/OrcaSlicer/)
    expect(r.printStartLine).toMatch(/^PRINT_START/)
  })
})

describe('analyze', () => {
  const f = analyze(scan(ORCA), facts)
  const titles = f.map((x) => x.title)
  it('flags unknown commands with fixes', () => {
    expect(titles).toContain('Unknown command G2')
    expect(titles).toContain('Unknown command M191')
    expect(f.find((x) => x.title === 'Unknown command G2')!.fix).toMatch(/gcode_arcs/)
  })
  it('flags tools that do not exist', () => {
    expect(f.find((x) => x.title === 'Unknown command T3')!.detail).toMatch(/only has T0, T1/)
  })
  it('flags single-extruder multi-material mode', () => {
    expect(titles).toContain('Slicer is set to single-nozzle multi-material, not a tool changer')
  })
  it('flags nozzle mismatch for used tools', () => {
    const n = f.find((x) => x.title.startsWith('Nozzle size'))!
    expect(n.severity).toBe('warning')
  })
  it('flags PRINT_START params the macro ignores', () => {
    expect(f.find((x) => x.title.startsWith('PRINT_START'))!.detail).toMatch(/T0_TEMP/)
  })
  it('does not flag zero extruder offsets', () => {
    expect(titles.some((t) => t.includes('offsets'))).toBe(false)
  })
  it('snippet mode allows placeholders', () => {
    const r = analyze(scan('PRINT_START TOOL=[initial_tool]\nT[next_extruder]\nFOO_BAR', true), facts, true)
    expect(r.map((x) => x.title)).toEqual(['Unknown command FOO_BAR'])
  })
})

describe('macroParams', () => {
  it('finds params.X and params["X"]', () => {
    expect([...macroParams("{% set t = params.TOOL|default(0) %} {params['BED_TEMP']}")].sort()).toEqual(['BED_TEMP', 'TOOL'])
  })
})
