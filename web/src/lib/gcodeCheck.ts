// G-code / slicer-profile checker (framework-agnostic).
// Streams a gcode file (or a pasted snippet), finds every command used and
// checks it against what this Klipper actually has, plus slicer settings that
// commonly break tool changers.

export interface CommandUse {
  count: number
  firstLine: number
  sample: string
}

export interface ScanResult {
  lines: number
  commands: Map<string, CommandUse>
  toolsUsed: Set<number> // from T<n> commands
  tempTools: Set<number> // from M104/M109 T<n>
  placeholders: { line: number; text: string }[]
  slicer: string
  settings: Map<string, string> // "; key = value" pairs (Orca/Prusa/Super config block)
  printStartLine: string
}

export class GcodeScanner {
  private carry = ''
  private lineNo = 0
  readonly result: ScanResult = {
    lines: 0,
    commands: new Map(),
    toolsUsed: new Set(),
    tempTools: new Set(),
    placeholders: [],
    slicer: '',
    settings: new Map(),
    printStartLine: '',
  }
  /** Snippet mode: slicer placeholders like [next_extruder] are expected. */
  constructor(private snippet = false) {}

  push(chunk: string) {
    const text = this.carry + chunk
    const parts = text.split('\n')
    this.carry = parts.pop() ?? ''
    for (const line of parts) this.line(line)
  }

  end() {
    if (this.carry) this.line(this.carry)
    this.carry = ''
    this.result.lines = this.lineNo
    return this.result
  }

  private line(raw: string) {
    this.lineNo++
    const line = raw.replace(/\r$/, '')
    const r = this.result
    const semi = line.indexOf(';')
    if (semi >= 0) {
      const comment = line.slice(semi + 1).trim()
      if (this.lineNo < 20 && /generated by/i.test(comment) && !r.slicer) r.slicer = comment
      const kv = comment.match(/^([a-z0-9_]+) = (.*)$/i)
      if (kv) r.settings.set(kv[1], kv[2])
    }
    const code = (semi >= 0 ? line.slice(0, semi) : line).trim()
    if (!code) return
    const cmd = code.split(/\s+/, 1)[0].toUpperCase()
    // Klipper accepts "G1X10" style for classic commands; normalise them.
    const classic = cmd.match(/^([GMT])(\d+(?:\.\d+)?)/)
    const name = classic ? classic[1] + classic[2] : cmd
    if (/[[{]/.test(name)) {
      // e.g. "T[next_extruder]" in a pasted slicer snippet; reported as a
      // placeholder (files) or resolved by the slicer (snippets)
      if (!this.snippet && r.placeholders.length < 20) r.placeholders.push({ line: this.lineNo, text: code.slice(0, 160) })
      return
    }
    const use = r.commands.get(name)
    if (use) use.count++
    else r.commands.set(name, { count: 1, firstLine: this.lineNo, sample: code.slice(0, 160) })

    if (/^T\d+$/.test(name)) r.toolsUsed.add(parseInt(name.slice(1), 10))
    if (name === 'M104' || name === 'M109') {
      const t = code.match(/\bT(\d+)/i)
      if (t) r.tempTools.add(parseInt(t[1], 10))
    }
    if (name === 'PRINT_START' && !r.printStartLine) r.printStartLine = code
    if (!this.snippet && /\[[a-z_]+(\[[^\]]*\])?\]|\{[^}]*\}/i.test(code) && r.placeholders.length < 20) {
      r.placeholders.push({ line: this.lineNo, text: code.slice(0, 160) })
    }
  }
}

export type Severity = 'error' | 'warning' | 'info' | 'ok'

export interface Finding {
  severity: Severity
  title: string
  detail: string
  fix?: string
  lines?: string[]
}

export interface PrinterFacts {
  commands: Set<string> // printer.gcode.commands keys (upper case)
  tools: { number: number; nozzle: number | null; name: string }[]
  printStartParams: Set<string> // params.X referenced by the PRINT_START macro
  sections: Set<string> // configfile.config section names (lower case)
}

