export function analyze(scan: ScanResult, facts: PrinterFacts, snippet = false): Finding[] {
  const out: Finding[] = []
  const s = scan.settings

  // 1. Commands this printer does not have
  const unknown = [...scan.commands.entries()].filter(([name]) => !isKnown(name, facts))
  for (const [name, use] of unknown) {
    const known = KNOWN_UNKNOWN[name]
    const isTool = /^T\d+$/.test(name)
    out.push({
      severity: 'error',
      title: `Unknown command ${name}` + (use.count > 1 ? ` (used ${use.count}×)` : ''),
      detail: isTool
        ? `The file selects ${name}, but this printer only has ${facts.tools.map((t) => 'T' + t.number).join(', ')}.`
        : known
          ? known.why + ' Klipper will stop with "Unknown command".'
          : 'Klipper has no command or macro with this name and will stop with "Unknown command".',
      fix: isTool ? 'Assign the objects to existing tools in the slicer.' : known?.fix,
      lines: [`line ${use.firstLine}: ${use.sample}`],
    })
  }
  if (!unknown.length && scan.commands.size) {
    out.push({ severity: 'ok', title: `All ${scan.commands.size} commands exist on this printer`, detail: [...scan.commands.keys()].sort().join(', ') })
  }

  if (scan.placeholders.length) {
    out.push({
      severity: 'error',
      title: 'Unresolved slicer placeholders',
      detail: 'These lines still contain slicer variables, usually a typo in a custom G-code field.',
      lines: scan.placeholders.map((p) => `line ${p.line}: ${p.text}`),
    })
  }

  // 2. Tools referenced in temperature commands that do not exist
  const toolNums = new Set(facts.tools.map((t) => t.number))
  const badTemp = [...scan.tempTools].filter((n) => !toolNums.has(n))
  if (badTemp.length) {
    out.push({ severity: 'error', title: `Temperature set for missing tool(s) ${badTemp.map((n) => 'T' + n).join(', ')}`, detail: 'M104/M109 T<n> for a tool that is not configured fails.' })
  }

  if (snippet) return out

  // 3. Slicer profile checks (Orca/Prusa/Super config block)
  if (!s.size) {
    out.push({ severity: 'info', title: 'No slicer settings found in this file', detail: 'Profile checks (nozzle sizes, multi-material mode, offsets) need OrcaSlicer/PrusaSlicer/SuperSlicer G-code with its config block.' })
    return out
  }

  const semm = s.get('single_extruder_multi_material')
  if (semm === '1' && facts.tools.length > 1) {
    out.push({
      severity: 'error',
      title: 'Slicer is set to single-nozzle multi-material, not a tool changer',
      detail:
        'single_extruder_multi_material = 1 makes Orca treat T0..Tn as filaments fed into ONE nozzle (like an AMS/MMU): ' +
        'one set of temperatures and retraction for all tools, filament ramming/purging at every change, and no per-tool nozzle sizes or offsets.',
      fix: 'Orca → Printer settings → Basic information: untick "Single Extruder Multi Material", then set the number of extruders to your tool count (each extruder gets its own nozzle diameter, retraction and temperatures).',
    })
  }

  const nozzles = (s.get('nozzle_diameter') ?? '').split(',').map((x) => parseFloat(x)).filter((x) => !isNaN(x))
  if (nozzles.length) {
    const used = scan.toolsUsed.size ? [...scan.toolsUsed] : [0]
    const rows: string[] = []
    let mismatch = false
    for (const t of facts.tools) {
      const slicerNozzle = nozzles.length === 1 ? nozzles[0] : nozzles[t.number]
      if (slicerNozzle === undefined || t.nozzle === null) continue
      const bad = Math.abs(slicerNozzle - t.nozzle) > 0.001
      if (bad && used.includes(t.number)) mismatch = true
      rows.push(`T${t.number}: slicer ${slicerNozzle} mm, Klipper ${t.nozzle} mm${bad ? '  ← mismatch' : ''}${used.includes(t.number) ? '' : ' (not used in this file)'}`)
    }
    out.push({
      severity: mismatch ? 'warning' : 'ok',
      title: mismatch ? 'Nozzle size in the slicer does not match the tool config' : 'Nozzle sizes match',
      detail: mismatch
        ? 'Check which one is physically installed. A wrong slicer value gives over/under-extrusion; a wrong Klipper value can trigger "Extrude exceeds maximum cross-section".'
        : 'Slicer nozzle_diameter matches each tool\'s [extruder] nozzle_diameter.',
      fix: mismatch ? 'Fix nozzle_diameter in the tool\'s config (Tools tab → Edit) or the slicer printer profile.' : undefined,
      lines: rows,
    })
  }

  const slicerExtruders = nozzles.length
  if (semm !== '1' && slicerExtruders > 1 && slicerExtruders !== facts.tools.length) {
    out.push({ severity: 'warning', title: `Slicer has ${slicerExtruders} extruders, printer has ${facts.tools.length} tools`, detail: 'Tool numbers in the slicer map 1:1 to T0..Tn on the printer.' })
  }

  const offsets = s.get('extruder_offset')
  if (offsets && /[1-9]/.test(offsets.replace(/0x0/g, ''))) {
    out.push({
      severity: 'warning',
      title: 'Slicer extruder offsets are not zero',
      detail: `extruder_offset = ${offsets}. Klipper already applies each tool's gcode_x/y/z_offset, so offsets in the slicer are applied twice.`,
      fix: 'Set all extruder offsets to 0 in Orca → Printer settings → Extruder N.',
    })
  }

  // PRINT_START parameters
  if (scan.printStartLine && facts.printStartParams.size) {
    const passed = new Set([...scan.printStartLine.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)=/g)].map((m) => m[1].toUpperCase()))
    const unused = [...passed].filter((p) => !facts.printStartParams.has(p))
    const missing = [...facts.printStartParams].filter((p) => !passed.has(p))
    if (unused.length || missing.length) {
      out.push({
        severity: 'warning',
        title: 'PRINT_START parameters do not match the macro',
        detail:
          (unused.length ? `Passed but ignored by the macro: ${unused.join(', ')}. ` : '') +
          (missing.length ? `Used by the macro but not passed (defaults apply): ${missing.join(', ')}.` : ''),
        lines: [scan.printStartLine],
      })
    } else {
      out.push({ severity: 'ok', title: 'PRINT_START parameters match the macro', detail: scan.printStartLine })
    }
  }

  if (facts.tools.length > 1 && semm !== '1' && scan.toolsUsed.size > 1) {
    const prime = s.get('enable_prime_tower')
    if (prime === '1') out.push({ severity: 'info', title: 'Prime tower enabled', detail: 'Fine for a tool changer (primes each tool after pickup). Purge volumes only matter for single-nozzle multi-material.' })
  }

  return out
}

function isKnown(name: string, facts: PrinterFacts) {
  if (facts.commands.has(name)) return true
  // Klipper handles these internally without listing them
  return ['M110', 'M112', 'M115', 'M117', 'M400'].includes(name)
}

/** params.X / params['X'] names referenced in a macro's gcode. */
export function macroParams(gcode: string): Set<string> {
  const out = new Set<string>()
  for (const m of gcode.matchAll(/params\.([A-Za-z_][A-Za-z0-9_]*)|params\[['"]([A-Za-z_][A-Za-z0-9_]*)['"]\]/g)) {
    out.add((m[1] ?? m[2]).toUpperCase())
  }
  return out
}
